#!/usr/bin/env python3
"""Generate compact wild held-item tables from data/Species.c."""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SPECIES_C = ROOT / "data/Species.c"
OUT_C = ROOT / "src/field/wild_species_held_items.c"
OUT_H = ROOT / "include/constants/generated/wild_species_held_items.h"

BLOCK_PAT = re.compile(r"\[(SPECIES_[A-Z0-9_]+)\]\s*=\s*\{", re.M)
HELD_PAT = re.compile(
    r"\.wildHeldItems\s*=\s*\{\s*\.common\s*=\s*(ITEM_[A-Z0-9_]+),\s*"
    r"\.rare\s*=\s*(ITEM_[A-Z0-9_]+),",
    re.S,
)

# Wild berry holds use the Future-12 pool; species table keeps non-berry items only.
BERRY_HELD_ITEM_RE = re.compile(r"^ITEM_.+_BERRY$")


def sanitize_table_held_item(item: str) -> str:
    if item == "ITEM_NONE" or item == "ITEM_BERRY_JUICE":
        return item
    if BERRY_HELD_ITEM_RE.match(item):
        return "ITEM_NONE"
    return item


def parse_species_c(path: Path) -> list[tuple[str, str, str]]:
    text = path.read_text(encoding="utf-8", errors="replace")
    blocks = [(m.group(1), m.start()) for m in BLOCK_PAT.finditer(text)]
    blocks.append(("END", len(text)))
    rows: list[tuple[str, str, str]] = []
    for i in range(len(blocks) - 1):
        name, start = blocks[i]
        end = blocks[i + 1][1]
        chunk = text[start:end]
        m = HELD_PAT.search(chunk)
        if m:
            rows.append((name, m.group(1), m.group(2)))
    return rows


def main() -> None:
    rows = parse_species_c(SPECIES_C)
    if not rows:
        raise SystemExit("no wildHeldItems rows parsed from Species.c")

    OUT_H.parent.mkdir(parents=True, exist_ok=True)
    OUT_H.write_text(
        "#ifndef CONSTANTS_GENERATED_WILD_SPECIES_HELD_ITEMS_H\n"
        "#define CONSTANTS_GENERATED_WILD_SPECIES_HELD_ITEMS_H\n\n"
        "#include \"types.h\"\n"
        "#include \"constants/species.h\"\n\n"
        "#define WILD_SPECIES_HELD_ITEM_COUNT (MAX_SPECIES_INCLUDING_FORMS + 1)\n\n"
        "extern const u16 sWildSpeciesHeldCommon[WILD_SPECIES_HELD_ITEM_COUNT];\n"
        "extern const u16 sWildSpeciesHeldRare[WILD_SPECIES_HELD_ITEM_COUNT];\n\n"
        "#endif\n",
        encoding="utf-8",
    )

    lines = [
        '#include "constants/generated/wild_species_held_items.h"',
        '#include "constants/item.h"',
        '#include "constants/species.h"',
        "",
        "// Generated by scripts/build/gen_wild_species_held_items.py — do not edit.",
        "",
        "const u16 sWildSpeciesHeldCommon[WILD_SPECIES_HELD_ITEM_COUNT] = {",
    ]
    for name, common, _ in rows:
        lines.append(f"    [{name}] = {sanitize_table_held_item(common)},")
    lines.append("};")
    lines.append("")
    lines.append("const u16 sWildSpeciesHeldRare[WILD_SPECIES_HELD_ITEM_COUNT] = {")
    for name, _, rare in rows:
        lines.append(f"    [{name}] = {sanitize_table_held_item(rare)},")
    lines.append("};")
    lines.append("")

    OUT_C.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT_C} ({len(rows)} species rows)")


if __name__ == "__main__":
    main()
