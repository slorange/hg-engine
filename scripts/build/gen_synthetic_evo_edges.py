#!/usr/bin/env python3
"""Generate synthetic evolution edge tables from data/synthetic_evolution_thresholds.tsv."""

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SPECIES_H = ROOT / "include/constants/species.h"
TSV = ROOT / "data/synthetic_evolution_thresholds.tsv"
OUT_C = ROOT / "src/field/synthetic_evo_edges_data.c"
OUT_H = ROOT / "include/constants/generated/synthetic_evo_edges.h"
MAX_SYNTH_EDGES = 96

SPECIES_RE = re.compile(r"#define\s+(SPECIES_[A-Z0-9_]+)\s+(\d+)")
BRANCH_MAP = {
    "": 0,
    "random50": 1,
}


def load_species_enum(path: Path) -> dict[str, int]:
    enums: dict[str, int] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        match = SPECIES_RE.match(line.strip())
        if match:
            enums[match.group(1)] = int(match.group(2))
    return enums


def display_name_to_enum(name: str) -> str:
    cleaned = name.strip().replace(".", "").replace("-", " ")
    parts = cleaned.split()
    return "SPECIES_" + "_".join(part.upper() for part in parts)


def parse_tsv(path: Path, species_enums: dict[str, int]) -> list[tuple[int, int, int, int]]:
    edges: list[tuple[int, int, int, int]] = []
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines:
        return edges

    header = lines[0].split("\t")
    col = {name: idx for idx, name in enumerate(header)}

    for line in lines[1:]:
        if not line.strip():
            continue
        parts = line.split("\t")
        from_name = parts[col["from"]].strip()
        to_name = parts[col["to"]].strip()
        min_level = int(parts[col["min_level"]].strip())
        branch_key = parts[col["branch"]].strip() if "branch" in col else ""
        branch = BRANCH_MAP.get(branch_key)
        if branch is None:
            raise SystemExit(f"Unknown branch {branch_key!r} on line: {line}")

        from_enum = display_name_to_enum(from_name)
        to_enum = display_name_to_enum(to_name)
        if from_enum not in species_enums or to_enum not in species_enums:
            raise SystemExit(f"Unknown species on line: {line} ({from_enum} / {to_enum})")

        edges.append((species_enums[from_enum], species_enums[to_enum], min_level, branch))

    edges.sort(key=lambda row: (row[0], row[2], row[1]))
    return edges


def write_header(path: Path, edge_count: int):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        f"""#ifndef CONSTANTS_GENERATED_SYNTHETIC_EVO_EDGES_H
#define CONSTANTS_GENERATED_SYNTHETIC_EVO_EDGES_H

#include "types.h"

// Generated by scripts/build/gen_synthetic_evo_edges.py — do not edit.

#define SYNTHETIC_EVO_MAX_EDGES {MAX_SYNTH_EDGES}

enum SyntheticEvoBranch {{
    SYNTH_BRANCH_NONE = 0,
    SYNTH_BRANCH_RANDOM50 = 1,
}};

typedef struct SyntheticEvoEdge {{
    u16 from;
    u16 to;
    u8 minLevel;
    u8 branch;
}} SyntheticEvoEdge;

typedef struct SyntheticEvoEdgesData {{
    u16 count;
    SyntheticEvoEdge edges[SYNTHETIC_EVO_MAX_EDGES];
}} SyntheticEvoEdgesData;

#if defined(OVERLAY129)
extern u32 SyntheticEvoEdgesFieldAddr;
#define gSyntheticEvoEdgesPtr ((const SyntheticEvoEdgesData *)(SyntheticEvoEdgesFieldAddr))
#else
extern const SyntheticEvoEdgesData sSyntheticEvoEdgesData;
#define gSyntheticEvoEdgesPtr (&sSyntheticEvoEdgesData)
#endif

#endif
""",
        encoding="utf-8",
    )


def write_source(path: Path, edges: list[tuple[int, int, int, int]]):
    if len(edges) > MAX_SYNTH_EDGES:
        raise SystemExit(f"Too many synthetic edges ({len(edges)} > {MAX_SYNTH_EDGES})")

    rows = []
    for from_id, to_id, min_level, branch in edges:
        rows.append(f"        {{ {from_id}, {to_id}, {min_level}, {branch} }},")

    body = "\n".join(rows) if rows else ""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        f"""#include "constants/generated/synthetic_evo_edges.h"

// Generated by scripts/build/gen_synthetic_evo_edges.py — do not edit.

const SyntheticEvoEdgesData sSyntheticEvoEdgesData = {{
    .count = {len(edges)},
    .edges = {{
{body}
    }},
}};
""",
        encoding="utf-8",
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--tsv", type=Path, default=TSV)
    parser.add_argument("--species-header", type=Path, default=SPECIES_H)
    parser.add_argument("--out-c", type=Path, default=OUT_C)
    parser.add_argument("--out-h", type=Path, default=OUT_H)
    args = parser.parse_args()

    species_enums = load_species_enum(args.species_header)
    edges = parse_tsv(args.tsv, species_enums)
    write_header(args.out_h, len(edges))
    write_source(args.out_c, edges)
    print(f"Wrote {args.out_c} ({len(edges)} edges)")
    print(f"Wrote {args.out_h}")


if __name__ == "__main__":
    main()
