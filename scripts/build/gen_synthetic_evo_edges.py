#!/usr/bin/env python3
"""Generate synthetic evolution edge tables from data/synthetic_evolution_thresholds.tsv."""

import argparse
import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SPECIES_H = ROOT / "include/constants/species.h"
TSV = ROOT / "data/synthetic_evolution_thresholds.tsv"
OUT_C = ROOT / "src/field/synthetic_evo_edges_data.c"
OUT_H = ROOT / "include/constants/generated/synthetic_evo_edges.h"
BABIES = ROOT / "data/encounter_babies.txt"
MAX_SYNTH_EDGES = 128
MAX_BABIES = 32
METHOD_MAP = {"fixed": 0, "natural_item": 1, "trainer_item": 2, "friendship": 3}

SPECIES_RE = re.compile(r"#define\s+(SPECIES_[A-Z0-9_]+)\s+(\d+)")
BRANCH_MAP = {
    "": 0,
    "random": 1,
}


def load_species_enum(path: Path) -> dict[str, int]:
    enums: dict[str, int] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        match = SPECIES_RE.match(line.strip())
        if match:
            enums[match.group(1)] = int(match.group(2))
    return enums


def display_name_to_enum(name: str) -> str:
    cleaned = name.strip().replace(".", "").replace("-", " ")
    parts = cleaned.split()
    return "SPECIES_" + "_".join(part.upper() for part in parts)


def parse_tsv(path: Path, species_enums: dict[str, int]):
    edges = []
    seen = set()
    with path.open(encoding="utf-8") as source:
        for row in csv.DictReader(source, delimiter="\t"):
            from_id = species_enums[display_name_to_enum(row["from"])]
            to_id = species_enums[display_name_to_enum(row["to"])]
            method = METHOD_MAP[row["method"]]
            level = int(row["min_level"] or 0)
            branch = BRANCH_MAP[row["branch"]]
            if not 0 <= level <= 100 or (method == 0 and level == 0):
                raise ValueError(f"Invalid threshold: {row}")
            if (from_id, to_id) in seen:
                raise ValueError(f"Duplicate evolution: {row}")
            seen.add((from_id, to_id))
            edges.append((from_id, to_id, level, branch, method))
    if len(edges) > MAX_SYNTH_EDGES:
        raise ValueError("Too many synthetic edges")
    edges.sort(key=lambda row: (row[0], row[2], row[1]))
    return edges


def load_babies(path, species_enums):
    names = [line.strip() for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]
    babies = [species_enums[display_name_to_enum(name)] for name in names]
    if len(babies) > MAX_BABIES or len(set(babies)) != len(babies):
        raise ValueError("Invalid baby species list")
    return babies


def write_header(path: Path, edge_count: int):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        f"""#ifndef CONSTANTS_GENERATED_SYNTHETIC_EVO_EDGES_H
#define CONSTANTS_GENERATED_SYNTHETIC_EVO_EDGES_H

#include "types.h"

// Generated by scripts/build/gen_synthetic_evo_edges.py — do not edit.

#define SYNTHETIC_EVO_MAX_EDGES {MAX_SYNTH_EDGES}
#define ENCOUNTER_MAX_BABIES {MAX_BABIES}

enum SyntheticEvoBranch {{
    SYNTH_BRANCH_NONE = 0,
    SYNTH_BRANCH_RANDOM = 1,
}};

enum EncounterEvoMethod {{
    ENCOUNTER_EVO_FIXED = 0,
    ENCOUNTER_EVO_NATURAL_ITEM = 1,
    ENCOUNTER_EVO_TRAINER_ITEM = 2,
    ENCOUNTER_EVO_FRIENDSHIP = 3,
}};

typedef struct SyntheticEvoEdge {{
    u16 from;
    u16 to;
    u8 minLevel;
    u8 branch;
    u8 method;
}} SyntheticEvoEdge;

typedef struct SyntheticEvoEdgesData {{
    u16 count;
    u16 babyCount;
    u16 babies[ENCOUNTER_MAX_BABIES];
    SyntheticEvoEdge edges[SYNTHETIC_EVO_MAX_EDGES];
}} SyntheticEvoEdgesData;

#if defined(OVERLAY129)
extern u32 SyntheticEvoEdgesFieldAddr;
#define gSyntheticEvoEdgesPtr ((const SyntheticEvoEdgesData *)(SyntheticEvoEdgesFieldAddr))
#else
extern const SyntheticEvoEdgesData sSyntheticEvoEdgesData;
#define gSyntheticEvoEdgesPtr (&sSyntheticEvoEdgesData)
#endif

#endif
""",
        encoding="utf-8",
    )


def write_source(path: Path, edges, babies):
    if len(edges) > MAX_SYNTH_EDGES:
        raise SystemExit(f"Too many synthetic edges ({len(edges)} > {MAX_SYNTH_EDGES})")

    rows = []
    for from_id, to_id, min_level, branch, method in edges:
        rows.append(f"        {{ {from_id}, {to_id}, {min_level}, {branch}, {method} }},")

    body = "\n".join(rows) if rows else ""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        f"""#include "constants/generated/synthetic_evo_edges.h"

// Generated by scripts/build/gen_synthetic_evo_edges.py — do not edit.

const SyntheticEvoEdgesData sSyntheticEvoEdgesData = {{
    .count = {len(edges)},
    .babyCount = {len(babies)},
    .babies = {{ {', '.join(map(str, babies))} }},
    .edges = {{
{body}
    }},
}};
""",
        encoding="utf-8",
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--tsv", type=Path, default=TSV)
    parser.add_argument("--babies", type=Path, default=BABIES)
    parser.add_argument("--species-header", type=Path, default=SPECIES_H)
    parser.add_argument("--out-c", type=Path, default=OUT_C)
    parser.add_argument("--out-h", type=Path, default=OUT_H)
    args = parser.parse_args()

    species_enums = load_species_enum(args.species_header)
    edges = parse_tsv(args.tsv, species_enums)
    write_header(args.out_h, len(edges))
    write_source(args.out_c, edges, load_babies(args.babies, species_enums))
    print(f"Wrote {args.out_c} ({len(edges)} edges)")
    print(f"Wrote {args.out_h}")


if __name__ == "__main__":
    main()
